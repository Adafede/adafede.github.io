/**
 * Emits public/_redirects for the URLs that used to be served by Quarto and are
 * now served under a different name, so hosts that read the file (Netlify,
 * Cloudflare Pages) do not need one HTML redirect page per URL.
 *
 * Eleventy has no redirect support of its own, so there are two artefacts:
 *  - public/_redirects      for hosts that read it (Netlify, Cloudflare Pages)
 *  - src/eleventy/redirect.njk  real HTML pages, for hosts that do not
 *                            (GitHub Pages)
 *
 * Both are derived from this file. Run: node scripts/site/generate-redirects.mjs
 * It is invoked by `npm run sync:content`, which runs after content migration.
 *
 * The direction matters: the Quarto URLs have been live for years, so they are
 * the ones that must keep resolving. Nothing here redirects a Quarto URL to a
 * new Eleventy-only name.
 */

import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const POSTS = join(ROOT, "src", "content", "posts");
const OUT = join(ROOT, "public", "_redirects");

/** Names this build used before it settled on the Quarto URLs. */
const PREVIOUS = {
  "blog.html": "/posts.html",
  // Quarto's standalone profiles page; the identifiers live on /articles.html.
  "articles/profiles.html": "/articles.html",
};

const slugs = existsSync(POSTS)
  ? readdirSync(POSTS)
      .filter((name) => name.endsWith(".md"))
      .map((name) => name.replace(/\.md$/, ""))
      .sort()
  : [];

const rows = [
  ...Object.entries(PREVIOUS).map(([from, to]) => [`/${from}`, to]),
  ...slugs.map((slug) => [`/blog/${slug}.html`, `/posts/${slug}.html`]),
];

const header = [
  "# Generated by scripts/site/generate-redirects.mjs — do not edit by hand.",
  "# URLs that changed name between builds -> the Quarto URL they now live at.",
  "# The HTML redirect pages under src/eleventy/redirect.njk cover hosts that",
  "# ignore this file (GitHub Pages).",
  "",
];

const body = rows.map(
  ([from, to]) => `${from.padEnd(42)} ${to.padEnd(42)} 301`,
);

mkdirSync(join(ROOT, "public"), { recursive: true });
writeFileSync(OUT, [...header, ...body].join("\n") + "\n", "utf-8");

console.log(`  + public/_redirects (${rows.length} rules)`);
